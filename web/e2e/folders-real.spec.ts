import { test, expect } from '@playwright/test'
import { existsSync, mkdirSync, readFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, resolve } from 'node:path'

const target = process.env.HARBOR_FOLDER_BROWSER_URL
const fixture = process.env.HARBOR_FOLDER_BROWSER_ROOT

test('native host filesystem: browser traversal, path entry, fresh listings, selection and cancel', async ({ page, request }) => {
  test.skip(!target || !fixture, 'explicit disposable host filesystem and real runner URL required')
  const root = resolve(fixture!)
  const marker = join(root, '.folder-browser-acceptance.json')
  expect(existsSync(marker), 'fixture ownership marker is required').toBe(true)
  expect(JSON.parse(readFileSync(marker, 'utf8')).disposable).toBe(true)
  const host = await (await request.get(`${target}/api/v1/host`)).json()
  expect(host.platform).toMatch(/^(darwin|linux)\//)
  expect(host.allowedRoots).toEqual([join(root, 'piers')])
  const initialRegistry = await (await request.get(`${target}/api/v1/ships`)).json()
  expect(initialRegistry).toEqual([])
  await page.goto(`${target}/#setup/existing`)
  const input = page.getByRole('textbox', { name: 'Pier folder' })
  const browse = page.getByRole('button', { name: 'Browse folders on host' })
  await browse.click()
  const dialog = page.getByRole('dialog', { name: 'Browse folders' })
  const location = dialog.getByRole('textbox', { name: 'Folder location' })
  await expect(location).toHaveValue(join(root, 'piers'))
  await dialog.getByRole('button', { name: 'Open folder Inside folder', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Open folder child', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Up one folder' }).click()
  await expect(location).toHaveValue(join(root, 'piers'))
  await dialog.getByRole('button', { name: 'Up one folder' }).click()
  await expect(location).toHaveValue(root)
  const createdName = `Created after browsing ${Date.now()}`
  mkdirSync(join(root, createdName))
  await location.press('Enter')
  await expect(dialog.getByRole('button', { name: `Open folder ${createdName}`, exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Open folder Another folder & spaces', exact: true }).click()
  await dialog.getByRole('button', { name: 'Open folder child', exact: true }).click()
  await expect(dialog.getByText('No visible folders.')).toBeVisible()
  const selected = join(root, 'Another folder & spaces', 'child')
  await dialog.getByRole('button', { name: 'Use this folder', exact: true }).click()
  await expect(input).toHaveValue(selected)
  await expect(browse).toBeFocused()
  await browse.click()
  await expect(location).toHaveValue(selected)
  await location.fill(join(root, 'missing folder'))
  await location.press('Enter')
  await expect(dialog.getByRole('alert')).toContainText('Folder is unavailable.')
  await expect(dialog.getByRole('button', { name: 'Use this folder', exact: true })).toBeDisabled()
  await location.fill(join(root, 'Another folder & spaces'))
  await location.press('Enter')
  await expect(dialog.getByRole('button', { name: 'Open folder child', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Open folder .hidden', exact: true })).toHaveCount(0)
  await dialog.getByRole('checkbox', { name: 'Show hidden folders' }).check()
  await expect(dialog.getByRole('button', { name: 'Open folder .hidden', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Home', exact: true }).click()
  await expect(location).toHaveValue(homedir())
  await dialog.getByRole('button', { name: 'Filesystem root', exact: true }).click()
  await expect(location).toHaveValue('/')
  await expect(dialog.getByRole('button', { name: 'Up one folder' })).toBeDisabled()
  await location.fill(join(root, 'Another folder & spaces'))
  await location.press('Enter')
  await expect(dialog.getByRole('button', { name: 'Open folder child', exact: true })).toBeVisible()
  const images = join(root, 'screenshots')
  mkdirSync(images, { recursive: true })
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 850 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const breadcrumbs = await dialog.getByRole('navigation', { name: 'Folder path' }).locator('button').evaluateAll(elements => elements.map(element => ({ width: element.clientWidth, content: element.scrollWidth })))
    expect(breadcrumbs.filter(crumb => crumb.content > crumb.width), 'breadcrumb labels must not overlap').toEqual([])
    await page.screenshot({ path: join(images, `browser-${host.platform.replace('/', '-')}-${width}.png`) })
  }
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(input).toHaveValue(selected)
  await expect(browse).toBeFocused()
  expect(await (await request.get(`${target}/api/v1/ships`)).json()).toEqual(initialRegistry)
  expect((await (await request.get(`${target}/api/v1/host`)).json()).allowedRoots).toEqual(host.allowedRoots)
})
