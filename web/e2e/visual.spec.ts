import { test, expect } from '@playwright/test'

test('welcome routes to three distinct setup paths and preserves non-secret values on Back', async ({ page }) => {
  await page.goto('/preview.html#welcome')
  await expect(page.getByRole('heading', { name: 'Welcome to Harbor' })).toBeVisible()
  await page.getByRole('button', { name: 'Create a comet' }).click()
  await page.getByLabel('Folder name').fill('my-comet')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Create a comet' }).click()
  await expect(page.getByLabel('Folder name')).toHaveValue('my-comet')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Boot from a keyfile' }).click()
  await expect(page.getByLabel('Ship identity')).toBeVisible()
  await expect(page.getByLabel('Keyfile')).toBeVisible()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Use an existing pier' }).click()
  await expect(page.getByLabel('Pier folder')).toBeVisible()
  await page.getByRole('button', { name: 'Upload an archive' }).click()
  await expect(page.getByLabel('Pier archive')).toBeVisible()
})

test('boot cannot open early and reconnects to its running job', async ({ page }) => {
  await page.goto('/preview.html#welcome')
  await page.getByRole('button', { name: 'Create a comet' }).click()
  await page.getByLabel('Folder name').fill('a-new-comet')
  await page.getByRole('button', { name: 'Boot comet' }).click()
  await expect(page.getByRole('heading', { name: 'Booting your ship' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open ship' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Your ship is ready' })).toBeVisible({ timeout: 10000 })
  await expect(page.getByRole('button', { name: 'Open ship' })).toBeEnabled()
})

test('maintenance edit persists and operation result is visible', async ({ page }) => {
  await page.goto('/preview.html?screen=ships')
  await page.getByRole('button', { name: 'Manage ~sampel-palnet' }).click()
  await page.getByRole('tab', { name: 'Maintenance' }).click()
  await page.getByRole('button', { name: 'Configure Pack' }).click()
  await page.getByLabel('Pack interval in days').fill('7')
  await page.getByRole('button', { name: 'Save schedule' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Configure Pack' })).toContainText('Every 7 days')
  await page.getByRole('button', { name: 'Run Pack now' }).click()
  await expect(page.getByRole('status')).toContainText('Pack completed', { timeout: 10000 })
})

test('failed operation stays visible without a fabricated success', async ({ page }) => {
  await page.goto('/preview.html?screen=ships&failure=pack')
  await page.getByRole('button', { name: 'Manage ~sampel-palnet' }).click()
  await page.getByRole('tab', { name: 'Maintenance' }).click()
  await page.getByRole('button', { name: 'Run Pack now' }).click()
  await expect(page.getByRole('alert')).toContainText('Pack could not complete')
})

test('stopped ship can start, terminal is reachable, and all narrow screens fit', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/preview.html?screen=ships')
  await page.getByRole('button', { name: 'Start ~mister-dister' }).click()
  await expect(page.getByRole('button', { name: 'Open ~mister-dister' })).toBeVisible()
  await page.getByRole('button', { name: 'Manage ~sampel-palnet' }).click()
  await page.getByRole('tab', { name: 'Terminal' }).click()
  await expect(page.getByLabel('Dojo command')).toBeVisible()
  await expect(page.getByRole('log')).toBeVisible()
  for (const tab of ['Overview', 'Maintenance', 'Terminal']) {
    await page.getByRole('tab', { name: tab, exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

test('primary navigation works from keyboard', async ({ page }) => {
  await page.goto('/preview.html#welcome')
  await expect(page.getByRole('heading', { name: 'Welcome to Harbor' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Boot from a keyfile' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Ship identity')).toBeVisible()
})

