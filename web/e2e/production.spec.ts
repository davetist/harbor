import { test, expect } from '@playwright/test'
const target = process.env.HARBOR_BROWSER_URL
test('real service navigation, terminal and Open use the connected host', async ({ page }) => {
  test.skip(!target, 'explicit disposable real service URL required')
  await page.goto(`${target}/`)
  await expect(page.getByRole('heading', { name: 'Your ships', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Sigil for ~zod', exact: true }).locator('svg')).toHaveCount(1)
  await expect(page.getByText('Visual prototype · simulated ships and operations')).toHaveCount(0)
  await page.screenshot({ path: '../output/playwright/real-pi-home.png' })
  await page.getByRole('button', { name: 'Manage fake-zod' }).click()
  await expect(page.locator('.detail-header').getByRole('img', { name: 'Sigil for ~zod', exact: true }).locator('svg')).toHaveCount(1)
  await page.getByRole('tab', { name: 'Terminal' }).click()
  await expect(page.getByLabel('Dojo command')).toBeVisible()
  await expect(page.locator('.xterm-rows')).toHaveCSS('font-family', /Menlo/)
  await page.getByLabel('Dojo command').fill('(add 5 6)')
  await page.getByRole('button', { name: 'Send' }).click()
  await expect(page.getByLabel('Dojo command')).toHaveValue('')
  await page.screenshot({ path: '../output/playwright/real-pi-terminal.png' })
  await page.getByRole('tab', { name: 'Maintenance' }).click()
  await expect(page.getByRole('button', { name: 'Run Pack now' })).toBeVisible()
  await page.screenshot({ path: '../output/playwright/real-pi-maintenance.png' })
  const ships: { name: string; webPort: number }[] = await (await page.request.get(`${target}/api/v1/ships`)).json()
  const current = ships.find(ship => ship.name === 'fake-zod')
  expect(current).toBeDefined()
  const popup = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'Open ship' }).click()
  const ship = await popup
  await ship.waitForLoadState()
  expect(new URL(ship.url()).port || '80').toBe(String(current!.webPort))
  await expect(ship.locator('input[type="password"]')).toBeVisible()
})

test('real Roll and Chop schedules preserve enablement when changing their shared cadence', async ({ page }) => {
  test.skip(!target, 'explicit disposable real service URL required')
  await page.goto(`${target}/#ships`)
  await page.getByRole('button', { name: 'Manage fake-zod' }).click()
  await page.getByRole('tab', { name: 'Maintenance' }).click()
  await page.getByRole('button', { name: 'Configure Chop' }).click()
  const chopEnabled = await page.getByLabel('Enabled', { exact: true }).isChecked()
  await page.getByRole('button', { name: 'Configure Roll' }).click()
  const interval = page.getByLabel('Roll interval in days')
  const previous = await interval.inputValue()
  const rollEnabled = await page.getByLabel('Enabled', { exact: true }).isChecked()
  try {
    await interval.fill('14')
    await page.getByRole('button', { name: 'Save schedule' }).click()
    await expect(page.getByRole('button', { name: 'Save schedule' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Configure Chop' }).click()
    await expect(page.getByLabel('Chop interval in days')).toHaveValue('14')
    await expect(page.getByLabel('Enabled', { exact: true })).toBeChecked({ checked: chopEnabled })
  } finally {
    await page.getByRole('button', { name: 'Configure Roll' }).click()
    await expect(page.getByLabel('Enabled', { exact: true })).toBeChecked({ checked: rollEnabled })
    await page.getByLabel('Roll interval in days').fill(previous)
    await page.getByRole('button', { name: 'Save schedule' }).click()
    await expect(page.getByRole('button', { name: 'Save schedule' })).toHaveCount(0)
  }
})
